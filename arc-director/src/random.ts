/** Mulberry32: numbers from 0 up to 1 that come out the same for the same `seed`, so a run can be made again. */
export function seeded(seed:number):()=>number {
	let a = seed;
	return () => {
		a = (a + 0x6D2B79F5) | 0;
		let t = Math.imul(a ^ (a >>> 15), 1 | a);
		t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
		return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
	};
}
